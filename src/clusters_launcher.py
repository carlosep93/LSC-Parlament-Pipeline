import copy
import json
import logging
import os
import time
from argparse import ArgumentParser, Namespace
from pathlib import Path
from typing import List

logging.basicConfig(format="[%(levelname)s]: %(message)s", level=logging.INFO)


def add_args(parser: ArgumentParser) -> None:
    parser.add_argument(
        "--process",
        choices=[
            "audio_extraction",
            "alignment",
            "segmentation",
            "video_segmentation",
            "dataset_generation",
            "extract_block_timestamps",
        ],
        type=str.lower,
        help="The name of the process you wish to run",
        required=True,
    )
    parser.add_argument(
        "--data-directory",
        "-d",
        help="The relative path to the pipeline data directory",
        required=True,
    )
    parser.add_argument("--session-id", "-s", help="The session id to process")
    parser.add_argument(
        "--ca-nemo-model",
        help="The path to the Catalan NeMo ASR model",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--es-nemo-model",
        help="The path to the Spanish NeMo ASR model",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--remote-storage",
        "-rs",
        help="Whether to use remote storage or store files in local",
    )
    parser.add_argument(
        "--sleep-time",
        "-t",
        help="Time (in seconds) in between sending jobs to the clusters",
        default=0,
        type=int,
    )
    parser.add_argument(
        "--max-jobs",
        "-j",
        help="Maximum number of jobs to send to the clusters every `sleep-time` seconds",
        default=300,
        type=int,
    )


def add_launcher_args(parser: ArgumentParser) -> None:
    parser.add_argument(
        "--sbatch",
        action="store_true",
        help="Use sbatch instead of bash do do each part in parallel.",
    )

    parser.add_argument(
        "--greasy",
        action="store_true",
        help="do not run, just print commands to greasy",
    )

    parser.add_argument("--greasy_path", type=str)


def generate_greasy_file(args: Namespace, script_path: Path) -> None:
    if not args.greasy_path:
        raise ValueError("If greasy is used, greasy_path must be specified")

    if os.path.exists(args.greasy_path):
        if args.overwrite_greasy:
            logging.info(
                "Greasy path {} already exists, overwriting".format(args.greasy_path)
            )
        else:
            raise ValueError("Greasy path {} already exists".format(args.greasy_path))
    else:
        logging.info("Greasy path {} does not exist, creating".format(args.greasy_path))

    os.makedirs(os.path.dirname(args.greasy_path), exist_ok=True)
    with open(args.greasy_path, "w") as f:
        f.write(
            f"# Greasy file automatically generated by {str(script_path)}\n# with arguments: {vars(args)}"
        )


def _launch_jobs(
    args: Namespace,
    args_copy: Namespace,
    session_ids: List[str],
    executer: str,
    script_path: Path,
) -> None:
    jobs = 1
    for id in session_ids:
        print(id)
        if jobs % args.max_jobs == 0:
            time.sleep(args.sleep_time)

        args_copy.session_id = id
        launch_script(args_copy, executer, script_path)
        jobs += 1


def launch_script(args: Namespace, executer: str, script_path: Path) -> None:
    if args.greasy:
        generate_greasy_file(args, script_path)
        with open(args.greasy_path, "a") as f:
            f.write("\n")
            f.write("[@ {} @]".format(os.getcwd()))
            f.write(" export args='{}'".format(json.dumps(vars(args))))
            f.write(f" && bash {str(script_path)}")
    else:
        os.environ["args"] = json.dumps(vars(args))
        os.system("{} {}".format(executer, str(script_path)))


def process_parlament(args: Namespace, executer: str, script_path: Path) -> None:
    # data_dir_pre2019 = Path(args.data_directory) / "segments"
    data_dir_post2019 = Path(args.data_directory) / "audios" if args.process != "audio_extraction" \
                        else Path(args.data_directory) / "videos" 

    args_copy = copy.deepcopy(args)

    session_ids = set()
    # for folder_name in os.listdir(data_dir_pre2019):
    # session_ids.add(folder_name)

    if args.process != "dataset_generation":
        for file in os.listdir(data_dir_post2019):
            session_id = "_".join(file.split("_")[:-1])
            session_ids.add(session_id)

    _launch_jobs(args, args_copy, session_ids, executer, script_path)


def main():
    parser = ArgumentParser()
    add_args(parser)
    add_launcher_args(parser)

    args = parser.parse_args()
    executer = "sbatch" if args.sbatch else "bash"
    script_path = Path("scripts") / f"run_{args.process}.sh"

    # If we specify one single session id
    if args.session_id:
        launch_script(args, executer, script_path)

    # Otherwise we process all session ids
    else:
        process_parlament(args, executer, script_path)


if __name__ == "__main__":
    main()
